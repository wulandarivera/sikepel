const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const common = require('/usr/lib/node_modules/pm2/lib/Common');
const raw = fs.readFileSync(path.join(__dirname, 'ecosystem.release.json'), 'utf8');
assert.equal(common.isConfigFile('ecosystem.release.json'), 'json');
assert.equal(common.isConfigFile('ecosystem.release.cjs'), null);
const {apps} = common.parseConfig(raw, 'ecosystem.release.json');
assert.equal(apps.length, 1);
const app = apps[0];
assert.equal(app.name, 'sikepel');
assert.equal(app.exec_mode, 'fork');
assert.equal(app.instances, 1);
assert.equal(app.cwd, '/home/cibodas/apps/sikepel/releases/e968338a106d672f0a7682d456a82567aadd080e');
assert.equal(app.script, 'node_modules/next/dist/bin/next');
assert.ok(fs.existsSync(path.join(app.cwd, app.script)));
assert.ok(fs.existsSync(path.join(app.cwd, '.next/BUILD_ID')));
assert.equal(JSON.parse(fs.readFileSync(path.join(app.cwd, 'package.json'))).version, '0.5.31');
const prepVersion = JSON.parse(fs.readFileSync(path.join(__dirname, 'package.json'))).version;
assert.equal(prepVersion, JSON.parse(fs.readFileSync(path.join(__dirname, 'package-lock.json'))).version);
assert.match(prepVersion, /^0\.5\.\d+$/);
assert.ok(!Object.keys(app.env).some(k => /PASSWORD|TOKEN|SECRET|DATABASE_URL/.test(k)));
console.log('PASS PM2 JSON parser, single Next target, immutable release, build, package versions, secret-free config');
console.log('No PM2 connect/start/restart or Next startup invoked');
